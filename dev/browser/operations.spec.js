import {test, expect} from '@playwright/test';
import fs from 'node:fs';

async function login(page, username) {
  await page.goto('/');
  await page.getByRole('button', {name: 'Sign in', exact: true}).click();
  await page.locator('#username').fill(username);
  await page.locator('#password').fill('demo-password');
  await page.locator('#kc-login').click();
  await expect(page.getByRole('heading', {name: 'Reconciliation overview'})).toBeVisible();
}
test('real Keycloak sign-in, search, human case resolution, audit and role controls', async ({page}) => {
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  const demo = JSON.parse(fs.readFileSync('/tmp/reconflow-demo-first.json', 'utf8'));
  const fee = demo.scenarios.find(row => row.name === 'provider_fee');
  await login(page, 'admin');
  await expect(page.locator('#identity')).toContainText('ADMIN');
  await expect(page).toHaveURL('http://localhost:18080/');
  expect(await page.evaluate(() => Object.keys(sessionStorage))).toEqual([]);
  expect(await page.evaluate(() => Object.keys(localStorage))).toEqual([]);
  await page.getByRole('button', {name: 'Internal transactions', exact: true}).click();
  await page.getByLabel('Order / business reference').fill(fee.reference);
  await page.getByRole('button', {name: 'Search', exact: true}).click();
  await expect(page.getByRole('cell', {name: fee.reference, exact: true})).toBeVisible();
  await page.getByRole('button', {name: 'Open', exact: true}).click();
  await page.getByRole('button', {name: 'View reconciliation', exact: true}).click();
  await expect(page.getByRole('heading', {name: 'Deterministic determination'})).toBeVisible();
  await expect(page.locator('#content')).toContainText('AMOUNT_MISMATCH');
  await expect(page.locator('#content')).toContainText('FEE_VARIANCE');
  await page.getByRole('button', {name: 'Open exception case'}).click();
  await expect(page.getByRole('heading', {name: 'Exception case', exact: true})).toBeVisible();
  await page.getByRole('button', {name: 'Start review', exact: true}).click();
  await expect(page.locator('.badge').first()).toHaveText('UNDER REVIEW');
  await page.getByLabel('Note', {exact: true}).fill('Reviewed the settlement gross, fee and net evidence.');
  await page.getByRole('button', {name: 'Add note', exact: true}).click();
  await expect(page.getByText('Reviewed the settlement gross, fee and net evidence.', {exact: true})).toBeVisible();
  await page.getByRole('button', {name: 'Request AI investigation'}).click();
  await expect(page.getByRole('status')).toContainText('AI investigation is not configured');
  await expect(page.locator('.badge').first()).toHaveText('UNDER REVIEW');
  await page.getByLabel('Resolution type').selectOption('ACCEPTED_FEE_VARIANCE');
  await page.getByLabel('Reason for resolution').fill('Human review confirmed the reported settlement fee explains the variance.');
  await page.getByLabel('Supporting evidence references').fill('reconciliation:' + fee.reconciliationId);
  await page.getByRole('checkbox').check();
  await page.getByRole('button', {name: 'Confirm resolution'}).click();
  await expect(page.locator('.badge').first()).toHaveText('RESOLVED');
  await expect(page.getByRole('button', {name: 'Confirm resolution'})).toHaveCount(0);
  await expect(page.getByRole('heading', {name: 'Human resolution'})).toBeVisible();
  await page.getByRole('button', {name: 'Load audit history', exact: true}).last().click();
  await expect(page.getByRole('cell', {name: 'CASE RESOLVED', exact: true})).toBeVisible();
  await page.getByRole('button', {name: 'View financial evidence'}).click();
  await expect(page.locator('.badge').first()).toHaveText('REVIEW REQUIRED');
  await page.getByRole('button', {name: 'Documentation', exact: true}).click();
  await expect(page.getByRole('button', {name: 'Import documentation'})).toBeVisible();
  await page.getByRole('button', {name: 'Sign out', exact: true}).click();
  await expect(page.getByRole('navigation')).toBeHidden();
  await login(page, 'viewer');
  await expect(page.locator('#identity')).toContainText('VIEWER');
  await expect(page.getByRole('button', {name: 'Documentation', exact: true})).toBeHidden();
  await expect(page.getByRole('button', {name: 'Record activity', exact: true})).toBeHidden();
  await page.getByRole('button', {name: 'Exception cases', exact: true}).click();
  await page.getByLabel('Case ID', {exact: true}).fill(fee.caseId);
  await page.getByRole('button', {name: 'Search', exact: true}).click();
  await expect(page.getByRole('cell', {name: fee.caseId, exact: true})).toBeVisible();
  await page.getByRole('button', {name: 'Open', exact: true}).click();
  await expect(page.locator('.badge').first()).toHaveText('RESOLVED');
  await expect(page.getByRole('button', {name: 'Confirm resolution'})).toHaveCount(0);
  expect(errors).toEqual([]);
});
test('rejects an unsolicited authorization callback without exchanging its code', async ({page}) => {
  let tokenRequests = 0;
  page.on('request', request => { if (request.url().includes('/protocol/openid-connect/token')) tokenRequests++; });
  await page.goto('/?code=untrusted&state=untrusted&iss=http://localhost:8180/realms/reconflow');
  await expect(page.getByRole('status')).toContainText('Sign-in could not be verified');
  await expect(page).toHaveURL('http://localhost:18080/');
  expect(tokenRequests).toBe(0);
});
